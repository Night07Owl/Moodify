class FAQ(models.Model):
    """
    Frequently Asked Question stored in SQL database.
    Feeds the FAQ knowledge base page and the AI Assistant grounding data.
    """
    CATEGORY_CHOICES = [
        ('General', 'General & Discovery'),
        ('Audio & Player', 'Audio & Player'),
        ('AI Assistant', 'AI Assistant & DJ'),
        ('Errors & Troubleshooting', 'Errors & Troubleshooting'),
        ('Account & Data', 'Account & Privacy'),
    ]

    question = models.CharField(max_length=255, help_text="The question title or prompt")
    answer = models.TextField(help_text="Detailed explanatory answer")
    category = models.CharField(max_length=50, choices=CATEGORY_CHOICES, default='General')
    order = models.PositiveIntegerField(default=0, help_text="Display sorting order")
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['order', 'id']
        verbose_name = "FAQ"
        verbose_name_plural = "FAQs"

    def __str__(self):
        return f"[{self.category}] {self.question}"


class ErrorCode(models.Model):
    """
    Standard and site-specific HTTP error codes stored in SQL.
    Used for the Error Code Reference directory and AI Assistant explanations.
    """
    CATEGORY_CHOICES = [
        ('Client Error', 'Client Error (4xx)'),
        ('Server Error', 'Server Error (5xx)'),
        ('Site-Specific', 'Site-Specific Error'),
    ]

    code = models.PositiveIntegerField(unique=True, help_text="HTTP or custom status code (e.g. 400, 404, 488)")
    name = models.CharField(max_length=120, help_text="Official or descriptive error title")
    category = models.CharField(max_length=50, choices=CATEGORY_CHOICES, default='Client Error')
    meaning = models.TextField(help_text="Clear definition of what this error code signifies")
    common_causes = models.TextField(help_text="Why this error occurs in web applications")
    troubleshooting_steps = models.TextField(help_text="Actionable steps the user or developer can take to fix it")
    is_site_specific = models.BooleanField(default=False, help_text="Check if this is a custom application error")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['code']
        verbose_name = "Error Code"
        verbose_name_plural = "Error Codes"

    def __str__(self):
        return f"{self.code} - {self.name}"


class SupportTicket(models.Model):
    """
    Support ticket stored in SQL database.
    Created when the AI Assistant cannot answer a query, or directly by the user.
    """
    STATUS_CHOICES = [
        ('Open', 'Open'),
        ('In Progress', 'In Progress'),
        ('Resolved', 'Resolved'),
        ('Closed', 'Closed'),
    ]
    PRIORITY_CHOICES = [
        ('Low', 'Low'),
        ('Medium', 'Medium'),
        ('High', 'High'),
        ('Urgent', 'Urgent'),
    ]

    ticket_number = models.CharField(max_length=32, unique=True, editable=False)
    user_name = models.CharField(max_length=120, default='Anonymous User')
    user_email = models.EmailField(help_text="Contact email for updates")
    subject = models.CharField(max_length=200, help_text="Summary of the issue")
    category = models.CharField(max_length=60, default='General Issue')
    description = models.TextField(help_text="Detailed problem report or query")
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='Open')
    priority = models.CharField(max_length=20, choices=PRIORITY_CHOICES, default='Medium')
    ai_generated = models.BooleanField(default=False, help_text="Auto-created by AI Assistant")
    resolution_notes = models.TextField(blank=True, help_text="Notes from the support engineer")
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-created_at']
        verbose_name = "Support Ticket"
        verbose_name_plural = "Support Tickets"

    def save(self, *args, **kwargs):
        if not self.ticket_number:
            import uuid
            self.ticket_number = f"TCK-{uuid.uuid4().hex[:8].upper()}"
        super().save(*args, **kwargs)

    def __str__(self):
        return f"{self.ticket_number} - {self.subject} ({self.status})"

