from django.db import models
from django.contrib.auth.models import User
from django.utils.text import slugify

class Mood(models.Model):
    """
    Represents one of the six core mood categories in Moodify:
    Happy, Sad, Chill, Energetic, Romantic, and Focus.
    """
    MOOD_CHOICES = [
        ('Happy', 'Happy'),
        ('Sad', 'Sad'),
        ('Chill', 'Chill'),
        ('Energetic', 'Energetic'),
        ('Romantic', 'Romantic'),
        ('Focus', 'Focus'),
    ]

    name = models.CharField(max_length=50, choices=MOOD_CHOICES, unique=True)
    slug = models.SlugField(max_length=60, unique=True, blank=True)
    tagline = models.CharField(max_length=160, help_text="Short expressive slogan for hero displays")
    description = models.TextField(blank=True, help_text="Detailed description of the mood vibes")
    icon = models.CharField(
        max_length=50, 
        default="headphones",
        help_text="Icon identifier (e.g., smile, cloud-rain, coffee, zap, heart, brain)"
    )
    gradient = models.CharField(
        max_length=150, 
        default="linear-gradient(135deg, #8b5cf6, #3b82f6)",
        help_text="CSS background gradient string"
    )
    accent_color = models.CharField(
        max_length=20, 
        default="#8b5cf6",
        help_text="Hex accent color for badges and glow effects"
    )
    order = models.PositiveSmallIntegerField(default=0)

    class Meta:
        ordering = ['order', 'name']
        verbose_name = "Mood"
        verbose_name_plural = "Moods"

    def save(self, *args, **kwargs):
        if not self.slug:
            self.slug = slugify(self.name)
        super().save(*args, **kwargs)

    def __str__(self):
        return self.name

    @property
    def song_count(self):
        return self.songs.count()


class Song(models.Model):
    """
    Represents an individual musical track curated under a specific Mood.
    Includes metadata, artwork URLs, external listening links (Spotify, YouTube),
    and an audio preview stream for the in-app player.
    """
    title = models.CharField(max_length=200)
    artist = models.CharField(max_length=200)
    album = models.CharField(max_length=200, blank=True)
    mood = models.ForeignKey(Mood, on_delete=models.CASCADE, related_name='songs')
    duration = models.CharField(max_length=10, default="3:30")
    genre = models.CharField(max_length=100, blank=True, default="Alternative")
    release_year = models.PositiveIntegerField(null=True, blank=True, default=2024)
    
    # Visuals & external links (No copyrighted audio files hosted locally)
    cover_image_url = models.URLField(
        max_length=500, 
        help_text="Direct HTTPS link to album or cover art image"
    )
    spotify_url = models.URLField(
        max_length=500, 
        blank=True, 
        help_text="Legitimate external listening link on Spotify"
    )
    spotify_track_id = models.CharField(
        max_length=100,
        blank=True,
        help_text="Spotify Track ID for the embedded Spotify Web Player"
    )
    youtube_url = models.URLField(
        max_length=500, 
        blank=True, 
        help_text="Legitimate external listening link on YouTube Music or YouTube"
    )
    youtube_video_id = models.CharField(
        max_length=100,
        blank=True,
        help_text="YouTube Video ID for the embedded YouTube Player"
    )
    audio_preview_url = models.URLField(
        max_length=500, 
        blank=True, 
        help_text="Royalty-free/Creative Commons sample audio stream for interactive browser player"
    )
    
    # Moodify AI Enhancements
    is_ai_generated = models.BooleanField(default=False, help_text="Generated by Moodify AI")
    ai_prompt = models.CharField(max_length=255, blank=True, help_text="Original user prompt or feeling that generated this track")
    energy_score = models.PositiveSmallIntegerField(default=50, help_text="Energy level 1-100%")

    description = models.TextField(blank=True, help_text="Short backstory or vibe of the track")
    is_featured = models.BooleanField(default=False, help_text="Pin as a featured recommendation")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-is_featured', '-created_at']
        verbose_name = "Song"
        verbose_name_plural = "Songs"

    def save(self, *args, **kwargs):
        import re
        # Auto-extract Spotify Track ID from URL if provided and not explicitly set
        if self.spotify_url and not self.spotify_track_id:
            match = re.search(r'track/([a-zA-Z0-9]+)', self.spotify_url)
            if match:
                self.spotify_track_id = match.group(1)

        # Auto-extract YouTube Video ID from URL if provided and not explicitly set
        if self.youtube_url and not self.youtube_video_id:
            yt_match = re.search(r'(?:v=|\/|youtu\.be\/|embed\/)([a-zA-Z0-9_-]{11})', self.youtube_url)
            if yt_match:
                self.youtube_video_id = yt_match.group(1)

        super().save(*args, **kwargs)

    def __str__(self):
        return f"{self.title} - {self.artist} ({self.mood.name})"

    @property
    def spotify_embed_url(self):
        if self.spotify_track_id:
            return f"https://open.spotify.com/embed/track/{self.spotify_track_id}?utm_source=generator&theme=0"
        return ""

    @property
    def youtube_embed_url(self):
        if self.youtube_video_id:
            return f"https://www.youtube.com/embed/{self.youtube_video_id}?autoplay=1&enablejsapi=1"
        return ""

    @property
    def youtube_music_url(self):
        if self.youtube_video_id:
            return f"https://music.youtube.com/watch?v={self.youtube_video_id}"
        from urllib.parse import quote_plus
        return f"https://music.youtube.com/search?q={quote_plus(self.title)}+{quote_plus(self.artist)}"

    @property
    def youtube_direct_url(self):
        if self.youtube_video_id:
            return f"https://www.youtube.com/watch?v={self.youtube_video_id}"
        from urllib.parse import quote_plus
        return f"https://www.youtube.com/results?search_query={quote_plus(self.title)}+{quote_plus(self.artist)}"

    @property
    def favorite_count(self):
        return self.favorited_by.count()

    def is_favorited_by(self, user):
        if not user.is_authenticated:
            return False
        return self.favorited_by.filter(user=user).exists()




class Favorite(models.Model):
    """
    Tracks which songs registered users have added to their favorites collection.
    """
    user = models.ForeignKey(User, on_delete=models.CASCADE, related_name='favorites')
    song = models.ForeignKey(Song, on_delete=models.CASCADE, related_name='favorited_by')
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        unique_together = ('user', 'song')
        ordering = ['-created_at']
        verbose_name = "Favorite"
        verbose_name_plural = "Favorites"

    def __str__(self):
        return f"{self.user.username} saved {self.song.title}"


